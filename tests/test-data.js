assert.equal(d.tracks[0].features[0],null,'Enrichment is non-mutating');
assert.equal(enriched.tracks[0].features[0],.5);
assert.equal(enriched.events.length,d.events.length);
assert.ok(enriched.models.spectrum[0]!==null);
assert.ok(enriched.tracks[0].families.includes('Folk/Acoustic'));
assert.throws(()=>core.mergeEnrichment(d,{...side,tracks:[{...side.tracks[0],features:{...side.tracks[0].features,energy:8}}]}),/energy/i);
assert.throws(()=>core.mergeEnrichment(d,{...side,tracks:[{...side.tracks[0],spotify_id:'unknown'}]}),/Spotify/i);
assert.throws(()=>core.validate({...d,meta:{...d.meta,eventArtists:[0]},events:[[0,999999,1]]}),/track/i);
const roundtrip=core.validate(JSON.parse(JSON.stringify(enriched)));
assert.equal(roundtrip.meta.eventMs,240000);
console.log('Importer, exact deduplication, privacy, validation, sidecar join, model generation and export round-trip passed.');
