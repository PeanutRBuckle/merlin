const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const corePath=path.join(__dirname,'../site/data-core.js');
assert.ok(fs.existsSync(corePath),'Browser importer has not been implemented');
const core=require(corePath);
const row={ts:'2024-01-01T12:00:00Z',ms_played:60000,master_metadata_track_name:'Synthetic song',master_metadata_album_artist_name:'Synthetic artist',master_metadata_album_album_name:'Synthetic album',spotify_track_uri:'spotify:track:0123456789ABCDEFGHIJKL',ip_addr:'192.0.2.1'};
