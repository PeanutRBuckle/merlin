const podcast={ts:'2024-01-03T12:00:00Z',ms_played:80000,episode_name:'Synthetic episode',spotify_episode_uri:'spotify:episode:0123456789ABCDEFGHIJKL'};
const d=core.convert([{name:'one.json',rows:[row,other,podcast]},{name:'two.json',rows:[{...row}, {...row,ip_addr:'192.0.2.2'}]}]);
assert.equal(d.events.length,3,'Exact full-record duplicate only; different source IP remains a distinct event');
assert.equal(d.meta.importReport.duplicates,1);
assert.equal(d.meta.importReport.excludedNonMusic,1);
assert.equal(d.meta.eventMs,240000);
assert.ok(!JSON.stringify(d).includes('192.0.2.'));
assert.equal(d.models.clusters['10'].assignment[0],-1);
assert.ok(d.events.every(e=>e[0]>=d.meta.first&&e[0]<=d.meta.last));
assert.throws(()=>core.convert([{name:'bad.json',rows:[{...row,ms_played:-1}]}]),/duration/i);
assert.throws(()=>core.convert([{name:'bad.json',rows:[{...row,ts:'nonsense'}]}]),/timestamp/i);
const side={format:'merlin-enrichment',version:1,tracks:[{spotify_id:'0123456789ABCDEFGHIJKL',features:{energy:.5,danceability:.4,valence:.2,acousticness:.7,instrumentalness:.1,speechiness:.02,loudness:-10,tempo:120},lastfm:{families:['Folk/Acoustic'],tags:['folk'],fetched_at:'2026-01-01T00:00:00Z'}}]};
