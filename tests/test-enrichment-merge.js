const assert=require('node:assert/strict');
const core=require('../site/data-core.js');
const id='0123456789ABCDEFGHIJKL';
const row={ts:'2024-01-01T00:00:00Z',ms_played:60000,master_metadata_track_name:'Synthetic track',master_metadata_album_artist_name:'Synthetic artist',spotify_track_uri:'spotify:track:'+id};
const base=core.convert([{name:'audio.json',rows:[row]}]);
const audio={energy:.5,danceability:.6,valence:.7,acousticness:.1,instrumentalness:0,speechiness:.03,loudness:-8,tempo:120};
const first=core.mergeEnrichment(base,{format:'merlin-enrichment',version:1,tracks:[{spotify_id:id,features:audio,lastfm:{families:['Rock'],tags:['rock']}}]});
const second=core.mergeEnrichment(first,{format:'merlin-enrichment',version:1,tracks:[{spotify_id:id,features:{tempo:121,energy:null},lastfm:{tags:['indie rock']}}]});
assert.equal(second.tracks[0].features[0],.5,'A later null must not erase an existing audio value');
assert.equal(second.tracks[0].features[7],121);
assert.deepEqual(second.tracks[0].families,['Rock'],'An omitted families key must not erase genres');
assert.ok(second.tracks[0].tags.includes('rock')&&second.tracks[0].tags.includes('indie rock'));
assert.equal(second.meta.enrichment.completeAudioTracks,1);
assert.equal(second.meta.enrichment.usableGenreTracks,1);
assert.equal(second.meta.enrichment.newCompleteAudioTracks,0);
assert.deepEqual(second.events,base.events);
const empty=core.mergeEnrichment(base,{format:'merlin-enrichment',version:1,tracks:[{spotify_id:id,lastfm:{families:[],tags:[]}}]});
assert.equal(empty.meta.enrichment.matched,1);
assert.equal(empty.meta.enrichment.completeAudioTracks,0);
assert.equal(empty.meta.enrichment.usableGenreTracks,0);
assert.deepEqual(empty.meta.enrichment.newViews,[]);
const genres=core.mergeEnrichment(base,{format:'merlin-enrichment',version:1,tracks:[{spotify_id:id,lastfm:{families:['Rock'],tags:['rock']}}]});
assert.deepEqual(genres.meta.enrichment.newViews,['genre']);
const features=core.mergeEnrichment(base,{format:'merlin-enrichment',version:1,tracks:[{spotify_id:id,features:audio},{spotify_id:'ZZZZZZZZZZZZZZZZZZZZZZ',features:audio}]});
assert.deepEqual(features.meta.enrichment.newViews,['spectrum','lanes']);
assert.equal(features.meta.enrichment.unmatched,1);
assert.equal(features.meta.enrichment.newCompleteAudioTracks,1);
const noRows=core.mergeEnrichment(base,{format:'merlin-enrichment',version:1,tracks:[]});
assert.equal(noRows.meta.enrichment.matched,0);assert.deepEqual(noRows.meta.enrichment.newViews,[]);
console.log('Incremental enrichment preserves prior values/labels, reports usable data and unlocks the correct views.');
